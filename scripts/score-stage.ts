/**
 * Scores a stage's snapshots against real results and writes the generated block of
 * data/events/<id>/accuracy.md (the "Lessons" text around it is written by the review-stage skill).
 * Uses engine/track-record.ts, the same scoring the site's Track record page shows.
 * Usage: node scripts/score-stage.ts <event-id> <stage-id>
 */
import { existsSync, globSync, readFileSync, writeFileSync } from 'node:fs'
import {
  Benchmarks,
  EventConfig,
  EventResults,
  EventTeams,
  Snapshot,
} from '../data/schemas/index.ts'
import { stageSeeds } from '../engine/swiss/stage-seeds.ts'
import { swissStandings } from '../engine/swiss/standings.ts'
import { stageTrackRecord } from '../engine/track-record.ts'
import { readJson, repoPath, repoRoot } from './lib/files.ts'

const [eventId, stageId] = process.argv.slice(2)
if (!eventId || !stageId) {
  console.error('Usage: node scripts/score-stage.ts <event-id> <stage-id>')
  process.exit(1)
}

const dir = repoPath('data/events', eventId)
const config = readJson(`${dir}/config.json`, EventConfig)
const stage = config.stages.find((s) => s.id === stageId)
if (stage?.type !== 'swiss') throw new Error(`${eventId}: no Swiss stage "${stageId}"`)
const results = readJson(`${dir}/results.json`, EventResults).matches
const teams = readJson(`${dir}/teams.json`, EventTeams)
const benchmarks = existsSync(`${dir}/benchmarks.json`)
  ? readJson(`${dir}/benchmarks.json`, Benchmarks).entries
  : []
const snapshots = globSync(`data/events/${eventId}/snapshots/${stageId}-r*.json`, {
  cwd: repoRoot,
}).map((path) => readJson(repoPath(path), Snapshot))
if (snapshots.length === 0) throw new Error(`No snapshots for ${stageId}`)

const standings = swissStandings(
  stageSeeds(teams.participants, stageId),
  results.filter((m) => m.stageId === stageId),
  stage,
)
const complete = standings.every((s) => s.status !== 'active')
const advanced = complete
  ? new Set(standings.filter((s) => s.status === 'advanced').map((s) => s.teamId))
  : undefined
const record = stageTrackRecord(stageId, snapshots, results, benchmarks, advanced)

const name = (id: string) => teams.participants.find((p) => p.teamId === id)?.displayName ?? id
const f3 = (x: number | undefined) => (x === undefined ? 'n/a' : x.toFixed(3))
const pct = (x: number | undefined) => (x === undefined ? 'n/a' : `${Math.round(x * 100)}%`)
const scored = record.rounds.reduce((sum, r) => sum + r.matches.length, 0)
const playedRounds = record.rounds.filter((r) => r.matches.length > 0)

const lines = [
  `<!-- score:${stageId}:start (generated by scripts/score-stage.ts; do not edit) -->`,
  `### ${stage.name}: scores (${new Date().toISOString().slice(0, 10)})`,
  '',
  `- Matches scored: ${scored} from ${record.snapshotRounds.length} snapshot(s); ${record.pending} still to play`,
  `- Brier (matches): ${f3(record.brier)} · coin flip 0.250 · favourite hit rate ${pct(record.hitRate)}`,
  record.market
    ? `- Same ${record.market.matches} matches, market benchmark: model ${f3(record.market.model)} vs market ${f3(record.market.market)}`
    : '- Market benchmark: no entries in benchmarks.json',
  record.advance
    ? `- Brier (advance, pre-stage snapshot): ${f3(record.advance.brier)}`
    : '- Advance odds: scored once the stage is complete',
  '',
  'Per round:',
  '',
  '| Round | Matches | Favourite won | Brier |',
  '|---|---|---|---|',
  ...playedRounds.map((r) => `| ${r.round} | ${r.matches.length} | ${r.hits} | ${f3(r.brier)} |`),
  '',
  'Calibration (matches):',
  '',
  '| Predicted | Matches | Avg predicted | Happened |',
  '|---|---|---|---|',
  ...record.calibration.map(
    (b) =>
      `| ${pct(b.from)}-${pct(b.to)} | ${b.count} | ${pct(b.predicted)} | ${pct(b.observed)} |`,
  ),
  '',
  'Upsets (the winner had under 40%):',
  ...(record.upsets.length
    ? record.upsets.map(
        (m) =>
          `- R${m.round} ${name(m.winner)} beat ${name(m.winner === m.teamA ? m.teamB : m.teamA)} (we gave ${pct(m.pWinner)})`,
      )
    : ['- none']),
  `<!-- score:${stageId}:end -->`,
]

const accuracyPath = `${dir}/accuracy.md`
const existing = existsSync(accuracyPath)
  ? readFileSync(accuracyPath, 'utf8')
  : `# ${config.name}: accuracy\n\nScores are generated; lessons below each block are written in the stage review.\n`
const block = lines.join('\n')
const pattern = new RegExp(`<!-- score:${stageId}:start[\\s\\S]*?<!-- score:${stageId}:end -->`)
const next = pattern.test(existing)
  ? existing.replace(pattern, block)
  : `${existing.trimEnd()}\n\n${block}\n\n#### Lessons\n- (written in the stage review)\n`
writeFileSync(accuracyPath, next)
console.log(block)
