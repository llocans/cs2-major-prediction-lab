/**
 * Scores a stage's snapshots against real results and writes the generated block of
 * data/events/<id>/accuracy.md (the "Lessons" text around it is written by the review-stage skill).
 * Usage: node scripts/score-stage.ts <event-id> <stage-id>
 */
import { existsSync, globSync, readFileSync, writeFileSync } from 'node:fs'
import {
  Benchmarks,
  EventConfig,
  EventResults,
  EventTeams,
  Snapshot,
} from '../data/schemas/index.ts'
import { brierScore, calibration, hitRate, type Scored } from '../engine/scoring.ts'
import { stageSeeds } from '../engine/swiss/stage-seeds.ts'
import { swissStandings } from '../engine/swiss/standings.ts'
import { readJson, repoPath, repoRoot } from './lib/files.ts'

const [eventId, stageId] = process.argv.slice(2)
if (!eventId || !stageId) {
  console.error('Usage: node scripts/score-stage.ts <event-id> <stage-id>')
  process.exit(1)
}

const dir = repoPath('data/events', eventId)
const config = readJson(`${dir}/config.json`, EventConfig)
const stage = config.stages.find((s) => s.id === stageId)
if (stage?.type !== 'swiss') throw new Error(`${eventId}: no Swiss stage "${stageId}"`)
const results = readJson(`${dir}/results.json`, EventResults).matches.filter(
  (m) => m.stageId === stageId,
)
const teams = readJson(`${dir}/teams.json`, EventTeams)
const benchmarks = existsSync(`${dir}/benchmarks.json`)
  ? readJson(`${dir}/benchmarks.json`, Benchmarks).entries.filter((b) => b.stageId === stageId)
  : []
const snapshots = globSync(`data/events/${eventId}/snapshots/${stageId}-r*.json`, { cwd: repoRoot })
  .map((path) => readJson(repoPath(path), Snapshot))
  .sort((a, b) => a.beforeRound - b.beforeRound)
if (snapshots.length === 0) throw new Error(`No snapshots for ${stageId}`)

const key = (round: number, a: string, b: string) => `${round}|${[a, b].sort().join('|')}`
const resultByKey = new Map(results.map((m) => [key(m.round, m.teamA, m.teamB), m]))
const name = (id: string) => teams.participants.find((p) => p.teamId === id)?.displayName ?? id

// Match predictions: each snapshot's matches are the round it was saved before.
const matchScores: Scored[] = []
const marketScores: Scored[] = []
const modelOnMarket: Scored[] = []
const misses: string[] = []
for (const snapshot of snapshots) {
  for (const match of snapshot.matches) {
    const result = resultByKey.get(key(snapshot.beforeRound, match.teamA, match.teamB))
    if (!result) continue
    const outcome: 0 | 1 = result.winner === match.teamA ? 1 : 0
    matchScores.push({ p: match.pA, outcome })
    if (Math.abs(match.pA - outcome) > 0.6) {
      misses.push(
        `R${snapshot.beforeRound} ${name(result.winner)} beat ${name(result.winner === match.teamA ? match.teamB : match.teamA)} (we gave ${Math.round((1 - Math.abs(match.pA - outcome)) * 100)}%)`,
      )
    }
    const market = benchmarks.find(
      (b) =>
        b.round === snapshot.beforeRound &&
        key(b.round, b.teamA, b.teamB) === key(snapshot.beforeRound, match.teamA, match.teamB),
    )
    if (market) {
      const marketPA = market.teamA === match.teamA ? market.pA : 1 - market.pA
      marketScores.push({ p: marketPA, outcome })
      modelOnMarket.push({ p: match.pA, outcome })
    }
  }
}

// Team outcomes from the pre-stage snapshot, once the stage is complete.
const seeds = stageSeeds(teams.participants, stageId)
const rules = {
  winsToAdvance: stage.winsToAdvance,
  lossesToEliminate: stage.lossesToEliminate,
  initialPairing: stage.initialPairing,
}
const standings = swissStandings(seeds, results, rules)
const complete = standings.every((s) => s.status !== 'active')
const first = snapshots[0]
const advanceScores: Scored[] = []
if (complete && first?.beforeRound === 1) {
  for (const team of first.teams) {
    const final = standings.find((s) => s.teamId === team.teamId)
    if (final)
      advanceScores.push({ p: team.pAdvance, outcome: final.status === 'advanced' ? 1 : 0 })
  }
}

const f3 = (x: number) => (Number.isFinite(x) ? x.toFixed(3) : 'n/a')
const pct = (x: number) => (Number.isFinite(x) ? `${Math.round(x * 100)}%` : 'n/a')
const lines = [
  `<!-- score:${stageId}:start (generated by scripts/score-stage.ts; do not edit) -->`,
  `### ${stage.name}: scores (${new Date().toISOString().slice(0, 10)})`,
  '',
  `- Matches scored: ${matchScores.length} from ${snapshots.length} snapshot(s)`,
  `- Brier (matches): ${matchScores.length ? f3(brierScore(matchScores)) : 'n/a'} · coin flip 0.250 · favourite hit rate ${pct(hitRate(matchScores))}`,
  marketScores.length
    ? `- Same ${marketScores.length} matches, market benchmark: model ${f3(brierScore(modelOnMarket))} vs market ${f3(brierScore(marketScores))}`
    : '- Market benchmark: no entries in benchmarks.json',
  advanceScores.length
    ? `- Brier (advance, 16 teams, pre-stage snapshot): ${f3(brierScore(advanceScores))}`
    : `- Advance odds: scored once the stage is complete${complete ? ' (no round 1 snapshot)' : ''}`,
  '',
  'Calibration (matches):',
  '',
  '| Predicted | Matches | Avg predicted | Happened |',
  '|---|---|---|---|',
  ...calibration(matchScores).map(
    (b) =>
      `| ${pct(b.from)}-${pct(b.to)} | ${b.count} | ${pct(b.predicted)} | ${pct(b.observed)} |`,
  ),
  '',
  'Biggest upsets (the winner had under 40%):',
  ...(misses.length ? misses.map((m) => `- ${m}`) : ['- none']),
  `<!-- score:${stageId}:end -->`,
]

const accuracyPath = `${dir}/accuracy.md`
const existing = existsSync(accuracyPath)
  ? readFileSync(accuracyPath, 'utf8')
  : `# ${config.name}: accuracy\n\nScores are generated; lessons below each block are written in the stage review.\n`
const block = lines.join('\n')
const pattern = new RegExp(`<!-- score:${stageId}:start[\\s\\S]*?<!-- score:${stageId}:end -->`)
const next = pattern.test(existing)
  ? existing.replace(pattern, block)
  : `${existing.trimEnd()}\n\n${block}\n\n#### Lessons\n- (written in the stage review)\n`
writeFileSync(accuracyPath, next)
console.log(block)
